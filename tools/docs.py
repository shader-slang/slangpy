def validate_agent_outputs(output_dir: Path) -> None:
    """Validate Markdown and machine-readable artifacts produced by an HTML build."""
    missing_markdown: list[str] = []
    source_paths = [
        path
        for path in DOCS_DIR.rglob("*.rst")
        if DOCS_DIR / "_build" not in path.parents and path != GENERATED_API_PATH
    ]
    source_paths.extend(
        path for path in (DOCS_DIR / "src" / "tutorials").glob("*.ipynb") if path.is_file()
    )
    for source_path in source_paths:
        relative = source_path.relative_to(DOCS_DIR).with_suffix(".md")
        if not (output_dir / relative).is_file():
            missing_markdown.append(relative.as_posix())
    if missing_markdown:
        raise DocumentationError(
            "Agent Markdown output is missing pages: " + ", ".join(sorted(missing_markdown))
        )

    representatives = {
        "src/basics/firstfunctions.md": ("# Your First Function", "```"),
        "generated/api/device.md": ("# Device", "slangpy.Device", "```python", "**Source:**"),
        "generated/api/functional-api.md": (
            "# Functional API",
            "slangpy.Module",
            "```python",
            "](#",
        ),
        "src/tutorials/compute_shader.md": ("# Compute Shader", "```c#"),
    }
    for relative, expected_values in representatives.items():
        text_value = (output_dir / relative).read_text(encoding="utf-8")
        missing_values = [value for value in expected_values if value not in text_value]
        if missing_values:
            raise DocumentationError(
                f"Agent Markdown page '{relative}' lost expected content: "
                + ", ".join(missing_values)
            )
        if "<nav" in text_value.lower():
            raise DocumentationError(f"Agent Markdown page contains HTML navigation: {relative}")

    llms_path = output_dir / "llms.txt"
    if not llms_path.is_file() or llms_path.read_text(encoding="utf-8") != _curated_llms_text():
        raise DocumentationError("llms.txt is missing or does not match the curated index")
    if (output_dir / "llms-full.txt").exists():
        raise DocumentationError("llms-full.txt must remain disabled for the expanded API")

    published_inventory = output_dir / "api" / "api.json"
    published_coverage = output_dir / "api" / "coverage.json"
    if not published_inventory.is_file() or not published_coverage.is_file():
        raise DocumentationError("Published agent API JSON files are missing")
    inventory = load_inventory(published_inventory)
    coverage = load_coverage_report(published_coverage)
    if coverage.package_version != inventory.package_version:
        raise DocumentationError("Published API and coverage versions do not match")
    if len(coverage.symbols) != len(inventory.symbols):
        raise DocumentationError("Published API and coverage symbol counts do not match")
    print(f"Validated {len(source_paths)} Markdown pages, curated llms.txt, and agent API JSON")


