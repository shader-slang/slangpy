class DocumentationError(RuntimeError):
    """Raised when documentation preparation or validation fails."""


@dataclass(frozen=True)
class PublicApiSection:
    """One ordered section in the reviewed public API contract."""

    id: str
    title: str
    audience: str
    names: tuple[str, ...] = ()
    patterns: tuple[str, ...] = ()


@dataclass(frozen=True)
class PublicApiConfig:
    """Reviewed public API configuration loaded from TOML."""

    schema_version: int
    package: str
    sections: tuple[PublicApiSection, ...]
    version_source: str | None = None
    package_version: str | None = None
    show_missing_documentation: bool = False


@dataclass
class DocumentationRecord:
    """Normalized documentation attached to an API symbol."""

    summary: str = ""
    body: str = ""
    parameters: dict[str, str] = field(default_factory=dict)
    returns: str = ""
    raises: list[str] = field(default_factory=list)
    status: str = "missing"


@dataclass
class SourceReference:
    """Repository-relative source location for an API symbol."""

    path: str
    line: int | None = None


@dataclass
class ApiSymbol:
    """Stable, renderer-independent representation of one public symbol."""

    name: str
    canonical_name: str
    kind: str
    section: str
    audience: str
    signatures: list[str] = field(default_factory=list)
    aliases: list[str] = field(default_factory=list)
    documentation: DocumentationRecord = field(default_factory=DocumentationRecord)
    source: SourceReference | None = None


@dataclass
class ApiInventory:
    """Versioned structured public API snapshot."""

    schema_version: int
    package_version: str
    sections: list[dict[str, str]]
    symbols: list[ApiSymbol]


@dataclass
class CoverageSymbol:
    """Mechanical documentation coverage result for one public symbol."""

    name: str
    status: str
    missing_parameters: list[str] = field(default_factory=list)
    requires_return: bool = False
    return_documented: bool = False
    has_examples: bool = False


@dataclass
class CoverageReport:
    """Versioned documentation coverage report."""

    schema_version: int
    package_version: str
    counts: dict[str, int]
    documented: int
    score: int
    symbols: list[CoverageSymbol]


