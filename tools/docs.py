def _search_terms(symbol: ApiSymbol) -> list[str]:
    parts = symbol.name.split(".")
    package_relative = ".".join(parts[1:])
    terms = [symbol.name, f"spy.{package_relative}", package_relative]
    if len(parts) >= 3:
        terms.append(".".join(parts[-2:]))
    terms.append(parts[-1])
    return list(dict.fromkeys(term for term in terms if len(term) >= 3))


def _search_repository(
    repository_root: Path,
    roots: Sequence[str],
    symbol: ApiSymbol,
    limit: int,
) -> list[RepositoryReference]:
    """Find deterministic, bounded repository references for a public symbol."""
    suffixes = {".cpp", ".h", ".hpp", ".ipynb", ".md", ".py", ".rst", ".slang"}
    terms = _search_terms(symbol)
    leaf = symbol.name.rsplit(".", 1)[-1]
    declaration_re = re.compile(
        rf"^\s*(?:class|struct|enum(?:\s+class)?)\s+(?:\w+\s+)*{re.escape(leaf)}\b"
    )
    binding_class_re = re.compile(rf"\bnb::class_<[^>]*\b{re.escape(leaf)}\b")
    matches: list[tuple[int, RepositoryReference]] = []
    for relative_root in roots:
        search_root = repository_root / relative_root
        if not search_root.is_dir():
            continue
        for path in sorted(search_root.rglob("*")):
            if (
                not path.is_file()
                or path.suffix.lower() not in suffixes
                or path.name == "py_doc.h"
                or (repository_root / "slangpy" / "tests" / "docs") in path.parents
                or path.stat().st_size > 5_000_000
            ):
                continue
            try:
                lines = path.read_text(encoding="utf-8").splitlines()
            except UnicodeDecodeError:
                continue
            best: tuple[int, int] | None = None
            for line_number, line in enumerate(lines, start=1):
                score = 0
                for index, term in enumerate(terms):
                    if term in line:
                        score = max(score, 100 - index * 10)
                if f'.def("{leaf}"' in line or f'.def_prop_ro("{leaf}"' in line:
                    score += 50
                if declaration_re.search(line):
                    score += 100
                if binding_class_re.search(line):
                    score += 100
                if score and (best is None or score > best[0]):
                    best = (score, line_number)
            if best is not None:
                relative = path.resolve().relative_to(repository_root.resolve()).as_posix()
                matches.append((best[0], RepositoryReference(relative, best[1])))
    matches.sort(key=lambda item: (-item[0], item[1].path, item[1].line))
    return [reference for _score, reference in matches[:limit]]


def _reference_link(reference: RepositoryReference | SourceReference) -> str:
    line = reference.line
    label = reference.path if line is None else f"{reference.path}:{line}"
    target = reference.path if line is None else f"{reference.path}#L{line}"
    return f"[{label}]({target.replace(' ', '%20')})"


def _related_symbols(inventory: ApiInventory, symbol: ApiSymbol, limit: int = 24) -> list[str]:
    related: list[str] = []
    names = {candidate.name for candidate in inventory.symbols}
    parent = symbol.name.rsplit(".", 1)[0]
    if parent in names:
        related.append(parent)
    prefix = f"{symbol.name}."
    related.extend(
        candidate.name
        for candidate in inventory.symbols
        if candidate.name.startswith(prefix) and "." not in candidate.name[len(prefix) :]
    )
    related.extend(symbol.aliases)
    for candidate in inventory.symbols:
        if candidate.name != symbol.name and candidate.canonical_name == symbol.canonical_name:
            related.append(candidate.name)
    fields = [
        symbol.documentation.summary,
        symbol.documentation.body,
        *symbol.documentation.parameters.values(),
        symbol.documentation.returns,
        *symbol.documentation.raises,
    ]
    for text_value in fields:
        for match in INTERNAL_PYTHON_REFERENCE_RE.finditer(text_value):
            target = match.group(1).strip().lstrip("~")
            titled_target = re.search(r"<([^>]+)>$", target)
            if titled_target:
                target = titled_target.group(1).strip().lstrip("~")
            if target in names:
                related.append(target)
    return list(dict.fromkeys(related))[:limit]


def generate_context(
    inventory: ApiInventory,
    symbol_name: str,
    repository_root: Path,
) -> str:
    """Generate a bounded Markdown context package for one public symbol."""
    symbols = {symbol.name: symbol for symbol in inventory.symbols}
    symbol = symbols.get(symbol_name)
    if symbol is None:
        raise DocumentationError(f"Public API symbol was not found: {symbol_name}")
    coverage_by_name = {
        coverage.name: coverage for coverage in calculate_coverage(inventory).symbols
    }
    coverage = coverage_by_name[symbol.name]
    native_backed = symbol.source is None or symbol.source.path.endswith(".pyi")
    declarations = (
        _search_repository(repository_root, ("src/sgl",), symbol, 8) if native_backed else []
    )
    bindings = (
        _search_repository(repository_root, ("src/slangpy_ext",), symbol, 8)
        if native_backed
        else []
    )
    tests = _search_repository(
        repository_root,
        ("slangpy/tests", "tests", "samples/tests"),
        symbol,
        12,
    )
    examples = _search_repository(
        repository_root,
        ("samples/tutorials", "samples/examples", "samples/experiments", "examples", "docs/src"),
        symbol,
        12,
    )
    related = _related_symbols(inventory, symbol)

    lines = [
        "<!-- schema_version: 1 -->",
        "",
        f"# Documentation context: `{symbol.name}`",
        "",
        f"- **Kind:** `{symbol.kind}`",
        f"- **Section:** `{symbol.section}`",
        f"- **Audience:** `{symbol.audience}`",
        f"- **Canonical name:** `{symbol.canonical_name}`",
        f"- **Coverage status:** `{coverage.status}`",
        "",
        "## Signatures",
        "",
    ]
    if symbol.signatures:
        lines.extend(["```python", *symbol.signatures, "```"])
    else:
        lines.append("No signature metadata is available.")

    documentation = symbol.documentation
    lines.extend(["", "## Existing documentation", ""])
    if documentation.summary and documentation.summary.upper() != "N/A":
        lines.extend([documentation.summary, ""])
    else:
        lines.extend(["No summary is documented.", ""])
    if documentation.body:
        lines.extend([documentation.body, ""])
    if documentation.parameters:
        lines.extend(["### Parameters", ""])
        lines.extend(
            f"- `{name}`: {description or 'No description.'}"
            for name, description in documentation.parameters.items()
        )
        lines.append("")
    if documentation.returns:
        lines.extend(["### Returns", "", documentation.returns, ""])
    if documentation.raises:
        lines.extend(["### Raises", ""])
        lines.extend(f"- {raised}" for raised in documentation.raises)
        lines.append("")

    missing_fields = _coverage_missing_fields(coverage)
    lines.extend(["## Documentation gaps", ""])
    if missing_fields:
        lines.extend(f"- {field}" for field in missing_fields)
    else:
        lines.append("No mechanically detectable gaps.")

    lines.extend(["", "## Canonical source", ""])
    if symbol.source is not None:
        lines.append(f"- {_reference_link(symbol.source)}")
    else:
        lines.append("No source location is present in the static inventory.")

    def add_references(title: str, references: Sequence[RepositoryReference]) -> None:
        lines.extend(["", f"## {title}", ""])
        if references:
            lines.extend(f"- {_reference_link(reference)}" for reference in references)
        else:
            lines.append("None found by deterministic repository search.")

    add_references("Native declarations", declarations)
    add_references("Python binding locations", bindings)
    lines.extend(["", "## Related public symbols", ""])
    if related:
        lines.extend(f"- `{name}`" for name in related)
    else:
        lines.append("None identified.")
    add_references("Relevant tests", tests)
    add_references("Examples and narrative documentation", examples)
    lines.extend(
        [
            "",
            "## Authoring constraints",
            "",
            "Edit authoritative Python docstrings or C++ documentation comments, not generated files.",
            "Confirm behavioral claims in implementation or tests and keep examples executable or explicitly illustrative.",
            "",
        ]
    )
    return "\n".join(lines)


