def load_inventory(path: Path) -> ApiInventory:
    """Load and validate a renderer-independent API inventory."""
    if not path.is_file():
        raise DocumentationError(
            f"API inventory does not exist: {path}. Run 'python tools/docs.py inventory'."
        )
    try:
        text = path.read_text(encoding="utf-8")
        data = json.loads(text)
        sections = [
            {
                "id": str(section["id"]),
                "title": str(section["title"]),
                "audience": str(section["audience"]),
            }
            for section in data["sections"]
        ]
        symbols: list[ApiSymbol] = []
        for item in data["symbols"]:
            documentation_data = item["documentation"]
            documentation = DocumentationRecord(
                summary=str(documentation_data.get("summary", "")),
                body=str(documentation_data.get("body", "")),
                parameters={
                    str(name): str(description)
                    for name, description in documentation_data.get("parameters", {}).items()
                },
                returns=str(documentation_data.get("returns", "")),
                raises=[str(value) for value in documentation_data.get("raises", [])],
                status=str(documentation_data["status"]),
            )
            source_data = item.get("source")
            source = (
                SourceReference(
                    path=str(source_data["path"]),
                    line=int(source_data["line"]) if source_data.get("line") is not None else None,
                )
                if source_data is not None
                else None
            )
            symbols.append(
                ApiSymbol(
                    name=str(item["name"]),
                    canonical_name=str(item["canonical_name"]),
                    kind=str(item["kind"]),
                    section=str(item["section"]),
                    audience=str(item["audience"]),
                    signatures=[str(value) for value in item.get("signatures", [])],
                    aliases=[str(value) for value in item.get("aliases", [])],
                    documentation=documentation,
                    source=source,
                )
            )
        inventory = ApiInventory(
            schema_version=int(data["schema_version"]),
            package_version=str(data["package_version"]),
            sections=sections,
            symbols=symbols,
        )
    except (AttributeError, json.JSONDecodeError, KeyError, TypeError, ValueError) as exc:
        raise DocumentationError(f"Invalid API inventory: {path}") from exc

    if inventory.schema_version != 1:
        raise DocumentationError(
            f"Unsupported API inventory schema version: {inventory.schema_version}"
        )
    problems = _inventory_problems(text)
    if problems:
        raise DocumentationError(
            "API inventory contains environment-dependent data: " + ", ".join(problems)
        )
    section_ids = {section["id"] for section in inventory.sections}
    if len(section_ids) != len(inventory.sections):
        raise DocumentationError("API inventory section IDs must be unique")
    for section in inventory.sections:
        if not re.fullmatch(r"[a-z0-9]+(?:-[a-z0-9]+)*", section["id"]):
            raise DocumentationError(
                f"API inventory section ID is not a stable URL slug: {section['id']}"
            )
        if section["audience"] not in {"user", "extension-author"}:
            raise DocumentationError(
                f"API inventory section '{section['id']}' has an unsupported audience"
            )
    symbol_names: set[str] = set()
    for symbol in inventory.symbols:
        if symbol.name in symbol_names:
            raise DocumentationError(f"Duplicate symbol in API inventory: {symbol.name}")
        symbol_names.add(symbol.name)
        if symbol.section not in section_ids:
            raise DocumentationError(
                f"API symbol '{symbol.name}' refers to unknown section '{symbol.section}'"
            )
        if symbol.documentation.status not in {"missing", "placeholder", "summary", "complete"}:
            raise DocumentationError(
                f"API symbol '{symbol.name}' has invalid documentation status "
                f"'{symbol.documentation.status}'"
            )
        if symbol.source is not None:
            source_path = PurePosixPath(symbol.source.path)
            if source_path.is_absolute() or ".." in source_path.parts:
                raise DocumentationError(
                    f"API symbol '{symbol.name}' has a non-relative source path"
                )
    return inventory


def _signature_shape(signature: str) -> tuple[list[str], bool]:
    start = signature.find("(")
    if start < 0:
        return [], False
    depth = 0
    quote = ""
    escaped = False
    end = -1
    for index, character in enumerate(signature[start:], start=start):
        if quote:
            if escaped:
                escaped = False
            elif character == "\\":
                escaped = True
            elif character == quote:
                quote = ""
            continue
        if character in {'"', "'"}:
            quote = character
        elif character == "(":
            depth += 1
        elif character == ")":
            depth -= 1
            if depth == 0:
                end = index
                break
    if end < 0:
        return [], False

    parameters_text = signature[start + 1 : end]
    parts: list[str] = []
    part_start = 0
    nesting = 0
    quote = ""
    escaped = False
    for index, character in enumerate(parameters_text):
        if quote:
            if escaped:
                escaped = False
            elif character == "\\":
                escaped = True
            elif character == quote:
                quote = ""
            continue
        if character in {'"', "'"}:
            quote = character
        elif character in "([{":
            nesting += 1
        elif character in ")]}":
            nesting -= 1
        elif character == "," and nesting == 0:
            parts.append(parameters_text[part_start:index])
            part_start = index + 1
    parts.append(parameters_text[part_start:])

    parameters: list[str] = []
    for part in parts:
        value = part.strip()
        if not value or value in {"/", "*"}:
            continue
        value = value.lstrip("*")
        name = re.split(r"[:=]", value, maxsplit=1)[0].strip()
        if name and name not in {"self", "cls"}:
            parameters.append(name)

    return_annotation = signature[end + 1 :].strip()
    requires_return = False
    if return_annotation.startswith("->"):
        return_type = return_annotation.removeprefix("->").strip()
        requires_return = return_type not in {"", "None", "NoneType", "typing.NoneType"}
    return list(dict.fromkeys(parameters)), requires_return


def _documentation_has_examples(documentation: DocumentationRecord) -> bool:
    text = "\n".join((documentation.summary, documentation.body)).lower()
    return any(marker in text for marker in ("example:", "examples:", ".. code-block::", ">>>"))


def _coverage_status(symbol: ApiSymbol) -> CoverageSymbol:
    documentation = symbol.documentation
    all_text = [
        documentation.summary,
        documentation.body,
        *documentation.parameters.values(),
        documentation.returns,
        *documentation.raises,
    ]
    has_placeholder = any(value.strip().upper() == "N/A" for value in all_text)
    has_content = any(value.strip() and value.strip().upper() != "N/A" for value in all_text)
    has_summary = bool(
        documentation.summary.strip() and documentation.summary.strip().upper() != "N/A"
    )
    expected_parameters: list[str] = []
    requires_return = False
    for signature in symbol.signatures:
        parameters, signature_requires_return = _signature_shape(signature)
        expected_parameters.extend(parameters)
        requires_return = requires_return or signature_requires_return
    expected_parameters = list(dict.fromkeys(expected_parameters))
    documented_parameters = {
        name.split()[-1].lstrip("*") for name in documentation.parameters if name.strip()
    }
    missing_parameters = [name for name in expected_parameters if name not in documented_parameters]
    return_documented = bool(
        documentation.returns.strip() and documentation.returns.strip().upper() != "N/A"
    )

    if documentation.status == "placeholder" or (has_placeholder and not has_content):
        status = "placeholder"
    elif not has_content:
        status = "missing"
    elif has_summary and not missing_parameters and (not requires_return or return_documented):
        status = "complete"
    else:
        status = "summary"

    return CoverageSymbol(
        name=symbol.name,
        status=status,
        missing_parameters=missing_parameters,
        requires_return=requires_return,
        return_documented=return_documented,
        has_examples=_documentation_has_examples(documentation),
    )


def calculate_coverage(inventory: ApiInventory) -> CoverageReport:
    """Calculate mechanical documentation coverage for every public symbol."""
    symbols = [_coverage_status(symbol) for symbol in inventory.symbols]
    counts = {
        status: sum(symbol.status == status for symbol in symbols)
        for status in ("missing", "placeholder", "summary", "complete")
    }
    score_weights = {"missing": 0, "placeholder": 0, "summary": 1, "complete": 2}
    return CoverageReport(
        schema_version=1,
        package_version=inventory.package_version,
        counts=counts,
        documented=counts["summary"] + counts["complete"],
        score=sum(score_weights[symbol.status] for symbol in symbols),
        symbols=symbols,
    )


def _coverage_text(report: CoverageReport) -> str:
    return json.dumps(asdict(report), indent=2, ensure_ascii=True) + "\n"


def write_coverage_report(report: CoverageReport, output: Path) -> None:
    """Write a deterministic documentation coverage report."""
    text = _coverage_text(report)
    output.parent.mkdir(parents=True, exist_ok=True)
    if not output.is_file() or output.read_text(encoding="utf-8") != text:
        output.write_text(text, encoding="utf-8")


def load_coverage_report(path: Path) -> CoverageReport:
    """Load a checked-in documentation coverage baseline."""
    if not path.is_file():
        raise DocumentationError(
            f"Coverage baseline does not exist: {path}. Review and write an initial baseline."
        )
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
        report = CoverageReport(
            schema_version=int(data["schema_version"]),
            package_version=str(data["package_version"]),
            counts={str(name): int(value) for name, value in data["counts"].items()},
            documented=int(data["documented"]),
            score=int(data["score"]),
            symbols=[
                CoverageSymbol(
                    name=str(symbol["name"]),
                    status=str(symbol["status"]),
                    missing_parameters=[str(name) for name in symbol.get("missing_parameters", [])],
                    requires_return=bool(symbol.get("requires_return", False)),
                    return_documented=bool(symbol.get("return_documented", False)),
                    has_examples=bool(symbol.get("has_examples", False)),
                )
                for symbol in data["symbols"]
            ],
        )
    except (AttributeError, json.JSONDecodeError, KeyError, TypeError, ValueError) as exc:
        raise DocumentationError(f"Invalid coverage baseline: {path}") from exc
    if report.schema_version != 1:
        raise DocumentationError(
            f"Unsupported coverage baseline schema version: {report.schema_version}"
        )
    if set(report.counts) != {"missing", "placeholder", "summary", "complete"}:
        raise DocumentationError("Coverage baseline has invalid status counts")
    if len({symbol.name for symbol in report.symbols}) != len(report.symbols):
        raise DocumentationError("Coverage baseline contains duplicate symbols")
    return report


def validate_coverage(report: CoverageReport, baseline: Path) -> None:
    """Validate current documentation coverage against a reviewed baseline."""
    expected = load_coverage_report(baseline)
    current_by_name = {symbol.name: symbol for symbol in report.symbols}
    expected_by_name = {symbol.name: symbol for symbol in expected.symbols}
    problems: list[str] = []

    if report.documented < expected.documented:
        problems.append(
            f"documented symbol count decreased from {expected.documented} to "
            f"{report.documented}"
        )
    if report.score < expected.score:
        problems.append(f"coverage score decreased from {expected.score} to {report.score}")

    removed = sorted(set(expected_by_name) - set(current_by_name))
    if removed:
        problems.append("baseline symbols were removed: " + ", ".join(removed))

    regressed_complete = sorted(
        name
        for name, symbol in expected_by_name.items()
        if symbol.status == "complete"
        and name in current_by_name
        and current_by_name[name].status != "complete"
    )
    if regressed_complete:
        problems.append("completed symbols regressed: " + ", ".join(regressed_complete))

    new_undocumented = sorted(
        name
        for name, symbol in current_by_name.items()
        if name not in expected_by_name and symbol.status in {"missing", "placeholder"}
    )
    if new_undocumented:
        problems.append("new public symbols are undocumented: " + ", ".join(new_undocumented))

    new_placeholders = sorted(
        name
        for name, symbol in current_by_name.items()
        if symbol.status == "placeholder"
        and (name not in expected_by_name or expected_by_name[name].status != "placeholder")
    )
    if new_placeholders:
        problems.append("new placeholders were added: " + ", ".join(new_placeholders))

    if problems:
        details = "\n".join(f"  - {problem}" for problem in problems)
        raise DocumentationError(f"Documentation coverage regressed:\n{details}")


