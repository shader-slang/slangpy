def _configured_roots(
    section: PublicApiSection,
    inventory: ApiInventory,
) -> list[str]:
    roots = list(section.names)
    section_names = [symbol.name for symbol in inventory.symbols if symbol.section == section.id]
    for pattern in section.patterns:
        roots.extend(name for name in section_names if re.fullmatch(pattern, name))
    return list(dict.fromkeys(roots))


def calculate_documentation_tasks(
    inventory: ApiInventory,
    config: PublicApiConfig,
    section_id: str | None = None,
) -> list[DocumentationTask]:
    """Return incomplete documentation ordered by API priority then status."""
    section_priorities = {section.id: index for index, section in enumerate(config.sections)}
    if section_id is not None and section_id not in section_priorities:
        raise DocumentationError(f"Unknown public API section: {section_id}")
    roots_by_section = {
        section.id: _configured_roots(section, inventory) for section in config.sections
    }
    coverage_by_name = {symbol.name: symbol for symbol in calculate_coverage(inventory).symbols}
    status_priorities = {"missing": 0, "placeholder": 1, "summary": 2}
    indexed_tasks: list[tuple[tuple[int, int, int, str], DocumentationTask]] = []
    for symbol in inventory.symbols:
        coverage = coverage_by_name[symbol.name]
        if coverage.status == "complete" or (
            section_id is not None and symbol.section != section_id
        ):
            continue
        roots = roots_by_section[symbol.section]
        root_priority = len(roots)
        for index, root in enumerate(roots):
            if symbol.name == root or symbol.name.startswith(f"{root}."):
                root_priority = index
                break
        task = DocumentationTask(
            name=symbol.name,
            section=symbol.section,
            audience=symbol.audience,
            status=coverage.status,
            missing_fields=_coverage_missing_fields(coverage),
            source=symbol.source,
        )
        priority = (
            section_priorities[symbol.section],
            root_priority,
            status_priorities[coverage.status],
            symbol.name,
        )
        indexed_tasks.append((priority, task))
    return [task for _priority, task in sorted(indexed_tasks, key=lambda item: item[0])]


def _tasks_json(
    inventory: ApiInventory,
    tasks: Sequence[DocumentationTask],
    section_id: str | None,
) -> str:
    data = {
        "schema_version": 1,
        "package_version": inventory.package_version,
        "section": section_id,
        "count": len(tasks),
        "tasks": [asdict(task) for task in tasks],
    }
    return json.dumps(data, indent=2, ensure_ascii=True) + "\n"


def _tasks_markdown(
    inventory: ApiInventory,
    tasks: Sequence[DocumentationTask],
    section_id: str | None,
) -> str:
    scope = f"section `{section_id}`" if section_id is not None else "all reviewed sections"
    lines = [
        "<!-- schema_version: 1 -->",
        "",
        "# SlangPy documentation tasks",
        "",
        f"{len(tasks)} incomplete symbols in {scope} for package version `{inventory.package_version}`.",
        "",
    ]
    for task in tasks:
        fields = "; ".join(task.missing_fields) or "review documentation"
        source = f" - {_reference_link(task.source)}" if task.source is not None else ""
        lines.append(f"- [ ] `{task.name}` - **{task.status}** - {fields}{source}")
    return "\n".join(lines).rstrip() + "\n"


def tasks_command(
    inventory_path: Path,
    config_path: Path,
    section_id: str | None,
    output_format: str,
    output: Path | None,
) -> None:
    """Write or print prioritized documentation tasks."""
    inventory = load_inventory(inventory_path)
    config = load_public_api(config_path)
